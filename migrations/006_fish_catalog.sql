CREATE TABLE IF NOT EXISTS fish_definitions (
  fish_id INTEGER PRIMARY KEY,
  model_code TEXT NOT NULL UNIQUE,
  name TEXT,
  minimum_level INTEGER,
  minimum_size REAL,
  maximum_size REAL,
  base_experience INTEGER,
  base_gold INTEGER,
  bite_delay_min_ms INTEGER,
  bite_delay_max_ms INTEGER,
  enabled INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1))
);

CREATE TABLE IF NOT EXISTS map_fish (
  map_id INTEGER NOT NULL REFERENCES maps(id) ON DELETE CASCADE,
  fish_id INTEGER NOT NULL REFERENCES fish_definitions(fish_id) ON DELETE CASCADE,
  fishing_point INTEGER,
  minimum_level INTEGER,
  weight INTEGER NOT NULL DEFAULT 1 CHECK (weight > 0),
  PRIMARY KEY(map_id, fish_id, fishing_point)
);

CREATE INDEX IF NOT EXISTS idx_map_fish_lookup ON map_fish(map_id, fishing_point);

