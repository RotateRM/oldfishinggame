import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = process.argv[2] || 'C:\\Program Files (x86)\\Gamescampus\\FishingChamp';
const destination = path.join(root, 'local-client');
const executable = fs.readFileSync(path.join(source, 'FishingChamp.exe'));
const expectedHash = 'f76a869b79be6e0277641bcd1796119054580ed05028f8701611d5ede7d51d63';
if (crypto.createHash('sha256').update(executable).digest('hex') !== expectedHash) throw new Error('Client differs from inspected version; refusing fixed-offset patch.');
const offset = 0x64f624;
const original = Buffer.from('218.145.55.164\0', 'ascii');
if (!executable.subarray(offset, offset + original.length).equals(original)) throw new Error('Endpoint bytes do not match.');
if (fs.existsSync(destination)) throw new Error('local-client already exists; preserve it before preparing another copy.');
fs.cpSync(source, destination, { recursive: true, errorOnExist: true, force: false });
executable.fill(0, offset, offset + original.length);
Buffer.from('127.0.0.1\0', 'ascii').copy(executable, offset);
fs.writeFileSync(path.join(destination, 'FishingChamp.exe'), executable);
fs.writeFileSync(path.join(root, 'start-local-client.cmd'), '@echo off\r\ncd /d "%~dp0local-client"\r\nstart "" FishingChamp.exe\r\n');
console.log(`Prepared localhost client at ${destination}. Original installation unchanged.`);
